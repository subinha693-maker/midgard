import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';

// [확정] 생일 메모 원문 — 한 글자도 바뀌면 안 된다
const ORIGINAL = `바다 항해를 갈꺼야.
무책임한 말이지만,
아주 긴시간동안 집에 돌아오지 못할거야.
클로토, 너는 혼자서 스스로 굳게 살아갈 힘이 있어. 내가 그렇게 낳았으니까.
방향을 모르겠고, 길이 보이지 않는다면, 엽사가 되렴.
그리고 너만의 이야기를 스스로 만들어.
내 걱정은 하지마. 엄마가 어디가서 쉽게 죽을사람 같니?
중앙정부 때문이라면 더더욱,
아노마리 캡슐은, 정말로 강한힘이 없으면 해결이 되지 않는 상황이 아니라면 먹지는 마. 내가 항상 말했던거지?
아무튼. 생일 축하해. 클로토, 보고싶을거야.`;

describe('생일 메모', () => {
  it('원문과 한 글자도 다르지 않음', () => {
    expect(readFileSync('data/letters/생일메모.txt', 'utf8').replace(/\n+$/, '')).toBe(ORIGINAL);
  });
});
